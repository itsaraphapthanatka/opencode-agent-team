def load_templates():
    out = {}
    for p in sorted(TPL.rglob("*")):
        if p.is_file():
            out[p.relative_to(TPL).as_posix()] = p.read_text(encoding="utf-8")
    return out


def literal(templates):
    """Python source for the templates dict. Templates must be embeddable."""
    lines = ["EMBEDDED_TEMPLATES = {"]
    for key, text in templates.items():
        if "\\\\" in text or '"""' in text or not text.endswith("\n"):
            # A trailing newline keeps every literal's closing delimiter on its
            # own line; backslashes/triple-quotes would need escaping we avoid.
            sys.exit(f"cannot embed {key!r}: backslash, triple quote, or no trailing newline")
        lines.append(f"    {key!r}: \"\"\"{text}\"\"\",")
    lines.append("}")
    return "\n".join(lines) + "\n\n"


def build():
    templates = load_templates()
    src = SRC.read_text(encoding="utf-8")
    if MARKER not in src:
        sys.exit("render.py header changed; update MARKER in build-marketplace.py")

    body = src.replace(MARKER, REPLACEMENT, 1)
    _, sep, rest = body.partition("import argparse")
    if not sep:
        sys.exit("render.py no longer imports argparse where expected")

    gen = HEADER + CLASSES + literal(templates) + "import argparse" + rest

    if DIST.exists():
        shutil.rmtree(DIST)
    (DIST / "scripts").mkdir(parents=True)
    (DIST / "reference").mkdir()
    (DIST / "extras" / "commands").mkdir(parents=True)

    out = DIST / "scripts" / "agent-team-render.py"
    out.write_text(gen, encoding="utf-8")
    for srcf, dstf in [(MP / "SKILL.md", DIST / "SKILL.md"),
                       (MP / "README.md", DIST / "README.md"),
                       (ROOT / "LICENSE", DIST / "LICENSE"),
                       (ROOT / "reference" / "roles.md", DIST / "reference" / "roles.md"),
                       (ROOT / "extras" / "commands" / "agent-team.md",
                        DIST / "extras" / "commands" / "agent-team.md")]:
        shutil.copy(srcf, dstf)

    verify(templates)
    print(f"BUILT {DIST}")
    print(f"  scripts/agent-team-render.py  {out.stat().st_size / 1024:.1f} KB "
          f"({len(templates)} embedded templates)")
    print(f"  total files                   {sum(1 for p in DIST.rglob('*') if p.is_file())}")
    print("Next: cd dist && zip -r opencode-agent-team.zip opencode-agent-team -x '*.DS_Store'")


def verify(templates):
    """Round-trip the embedded literal and smoke-test a real render from a temp file."""
    import tempfile, subprocess, json as _json

    out = DIST / "scripts" / "agent-team-render.py"
    code = out.read_text(encoding="utf-8")

    # 1. The literal dict in the generated file must equal the source templates.
    ns = {}
    lit = ("EMBEDDED_TEMPLATES = {"
           + code.split("EMBEDDED_TEMPLATES = {", 1)[1].split("\n}\n", 1)[0]
           + "\n}")
    exec(compile(lit, str(out), "exec"), ns)
    if ns["EMBEDDED_TEMPLATES"] != templates:
        sys.exit("round-trip mismatch: embedded literal != source templates")
    print(f"  round-trip OK ({len(templates)} templates match source exactly)")

    # 2. Run the script the way Agensi does: copy it alone to a temp dir, render
    #    into a throwaway project, then --check the result.
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        script = tmp / "agent-team-render.py"
        shutil.copy(out, script)
        proj = tmp / "proj"
        docs = proj / "docs"
        proj.mkdir()
        cfg = {
            "project": "SmokeTest", "project_root": str(proj), "docs_dir": str(docs),
            "report_language": "English", "profile": "balanced", "compat_v1": True,
            "roles": ["product-manager", "architect", "backend-dev", "test-engineer",
                      "code-reviewer", "bug-triager", "tech-writer"],
            "repos": [{"name": "App", "path": str(proj), "stack": "Python",
                       "checks": ["python3 -m unittest discover -s tests"]}],
        }
        cfgp = proj / "agent-team.json"
        cfgp.write_text(_json.dumps(cfg), encoding="utf-8")
        r = subprocess.run(["python3", str(script), "--config", str(cfgp)],
                           capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"smoke render FAILED:\n{r.stdout}\n{r.stderr}")
        r2 = subprocess.run(["python3", str(script), "--config", str(cfgp), "--check"],
                            capture_output=True, text=True)
        if r2.returncode != 0:
            sys.exit(f"smoke --check FAILED:\n{r2.stdout}\n{r2.stderr}")
        agents = sorted(p.name for p in (proj / ".opencode" / "agents").glob("*.md"))
        if len(agents) != 7:
            sys.exit(f"smoke render wrote {len(agents)} agents, expected 7")
        print(f"  smoke render OK (ran from a lone temp file; {len(agents)} agents, --check clean)")


if __name__ == "__main__":
    build()
